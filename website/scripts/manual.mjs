// The public README is the single source for the application's reference guide.
export function readmeSection(readme, title, level = 2) {
  const marker = `${'#'.repeat(level)} ${title}`;
  const lines = readme.split('\n');
  const start = lines.findIndex(line => line === marker);
  if (start < 0) throw new Error(`Documentation source missing: ${marker}`);
  let inFence = false;
  let end = lines.length;
  for (let index = start + 1; index < lines.length; index++) {
    if (/^```/.test(lines[index])) inFence = !inFence;
    const heading = /^(#{1,6}) /.exec(lines[index]);
    if (!inFence && heading && heading[1].length <= level) {
      end = index;
      break;
    }
  }
  return lines.slice(start, end).join('\n').trim();
}

export function buildManual(readme, start, notes) {
  const section = title => readmeSection(readme, title);
  const themes = section('Themes');
  const customThemeStart = themes.indexOf('### Custom themes');
  if (customThemeStart < 0) throw new Error('Documentation source missing: custom themes');
  const pieces = [
    '<!-- Generated by scripts/prepare-docs.mjs. Edit README.md or src/content/, not this file. -->',
    start.trim(),
    section('Install').replace(/^## Install\n/, '## Installation\n'),
    section('Usage'),
    section('todo.txt format').replace(/^## todo\.txt format\n/, '## Tasks and subtasks\n'),
    section('Keybindings'),
    section('Mouse interaction'),
    section('Command-line interface'),
    section('Natural-language add'),
    section('Phone capture'),
    section('Configuration'),
    '## Themes\n\nPress `T` to choose between Muted Slate, Dawn, Nord, Matrix, and Terminal. Terminal respects your terminal palette. Custom themes can be added too.\n\n' + themes.slice(customThemeStart),
    readmeSection(readme, 'What this fork adds', 3).replace(/^### What this fork adds\n/, '## Fork additions\n'),
    notes.trim(),
  ];
  return pieces.join('\n\n')
    .replaceAll('](docs/themes)', '](https://github.com/Caracolaracol/tuxedo-task/tree/main/docs/themes)')
    .replaceAll('](#install)', '](#installation)') + '\n';
}
