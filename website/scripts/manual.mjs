import { readFile } from 'node:fs/promises';

// Ordered for first-time TUI use. Each guide is independently readable on GitHub.
export const guideSources = [
  ['installation.md', 'Installation'],
  ['getting-started.md', 'Getting started'],
  ['usage.md', 'Usage'],
  ['tasks.md', 'Tasks and subtasks'],
  ['keybindings.md', 'Keybindings'],
  ['mouse.md', 'Mouse interaction'],
  ['natural-language.md', 'Natural-language add'],
  ['phone-capture.md', 'Phone capture'],
  ['configuration.md', 'Configuration'],
  ['themes.md', 'Themes'],
  ['fork.md', 'Fork additions'],
  ['troubleshooting.md', 'Troubleshooting'],
  ['cli.md', 'Command-line interface'],
  ['support.md', 'Support and credits'],
];

export async function loadGuides() {
  return Object.fromEntries(await Promise.all(guideSources.map(async ([file]) => [
    file, await readFile(new URL(`../../Docs/${file}`, import.meta.url), 'utf8'),
  ])));
}

export function markdownSection(source, title, level = 2) {
  const marker = `${'#'.repeat(level)} ${title}`;
  const lines = source.split('\n');
  const start = lines.findIndex(line => line === marker);
  if (start < 0) throw new Error(`Documentation source missing: ${marker}`);
  let inFence = false;
  let end = lines.length;
  for (let index = start + 1; index < lines.length; index++) {
    if (/^```/.test(lines[index])) inFence = !inFence;
    const heading = /^(#{1,6}) /.exec(lines[index]);
    if (!inFence && heading && heading[1].length <= level) {
      end = index;
      break;
    }
  }
  return lines.slice(start, end).join('\n').trim();
}

const slug = title => title.toLowerCase().replace(/[^a-z0-9 -]/g, '').replaceAll(' ', '-');
const github = 'https://github.com/Caracolaracol/tuxedo-task';

export function buildManual(guides) {
  const pieces = guideSources.map(([file, title]) => {
    const source = guides[file];
    if (!source?.startsWith(`# ${title}\n`)) throw new Error(`Documentation source missing: ${file} / ${title}`);
    // GitHub-only navigation is unnecessary inside the single-page manual.
    const body = source.split('\n\n---\n\n[Documentation index]')[0].trim();
    let inFence = false;
    return body.split('\n').map(line => {
      if (line.startsWith('```')) inFence = !inFence;
      if (inFence) return line;
      return line.replace(/^(#{1,5}) /, '#$1 ').replace(/\]\(([^)]+)\)/g, (match, href) => {
        if (/^(?:https?:|#)/.test(href)) return match;
        const [path, fragment] = href.split('#');
        const guide = guideSources.find(([name]) => name === path);
        if (guide) return `](#${fragment || slug(guide[1])})`;
        if (path === 'themes') return `](${github}/tree/main/Docs/themes)`;
        // Non-guide references (licenses, gallery, developer docs) stay on GitHub.
        const relative = path.startsWith('../') ? path.slice(3) : `Docs/${path}`;
        return `](${github}/blob/main/${relative}${fragment ? `#${fragment}` : ''})`;
      });
    }).join('\n');
  });
  return '<!-- Generated by scripts/prepare-docs.mjs. Edit Docs/*.md, not this file. -->\n\n' + pieces.join('\n\n') + '\n';
}
